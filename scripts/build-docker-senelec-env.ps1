# Generate .env.docker-senelec from .env.senelec (SENELEC bureau + Docker)
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$src = Join-Path $root ".env.senelec"
$dst = Join-Path $root ".env.docker-senelec"

if (-not (Test-Path $src)) {
    throw "Missing file: $src"
}

$lines = Get-Content $src -Encoding UTF8
$dbLine = $lines | Where-Object { $_ -match '^\s*DATABASE_URL=' } | Select-Object -First 1
if (-not $dbLine) {
    throw "DATABASE_URL missing in .env.senelec"
}

$dbValue = ($dbLine -split '=', 2)[1].Trim()
$dbValue = $dbValue -replace 'ODBC\+Driver\+17\+for\+SQL\+Server', 'ODBC+Driver+18+for+SQL+Server'

$dns = Resolve-DnsName srv-bddomtech -ErrorAction SilentlyContinue | Where-Object { $_.IPAddress } | Select-Object -First 1
if (-not $dns) {
    throw "Cannot resolve srv-bddomtech - check SENELEC network"
}
$senelecDbIp = $dns.IPAddress
Write-Host "srv-bddomtech resolved to $senelecDbIp"

function Get-EnvValue([string]$name) {
    $line = $lines | Where-Object { $_ -match "^\s*$name=" } | Select-Object -First 1
    if ($line) { return ($line -split '=', 2)[1].Trim() }
    return ""
}

$secret = Get-EnvValue "SECRET_KEY"
if (-not $secret -or $secret -like "changeme*") {
    throw "SECRET_KEY absente ou valeur d'exemple dans .env.senelec (generer avec : openssl rand -hex 32)"
}

$startTls = Get-EnvValue "LDAP_START_TLS"
$accessTtl = Get-EnvValue "ACCESS_TOKEN_EXPIRE_MINUTES"
if (-not $accessTtl) { $accessTtl = "30" }
$refreshDays = Get-EnvValue "REFRESH_TOKEN_EXPIRE_DAYS"
if (-not $refreshDays) { $refreshDays = "7" }
$smtpPort = Get-EnvValue "SMTP_PORT"
if (-not $smtpPort) { $smtpPort = "587" }

$out = @(
    "# generated by build-docker-senelec-env.ps1",
    "SENELEC_DB_IP=$senelecDbIp",
    "DATABASE_URL=$dbValue",
    "",
    "REDIS_URL=redis://redis:6379/0",
    "CELERY_BROKER_URL=redis://redis:6379/1",
    "CELERY_RESULT_BACKEND=redis://redis:6379/2",
    "",
    "SECRET_KEY=$secret",
    "ACCESS_TOKEN_EXPIRE_MINUTES=$accessTtl",
    "REFRESH_TOKEN_EXPIRE_DAYS=$refreshDays",
    "",
    "ENVIRONMENT=development",
    "API_VERSION=v1",
    "CORS_ORIGINS=http://localhost:4210,http://127.0.0.1:4210,http://localhost:4200",
    "",
    "SMS_GATEWAY_URL=$(Get-EnvValue 'SMS_GATEWAY_URL')",
    "SMS_GATEWAY_API_KEY=$(Get-EnvValue 'SMS_GATEWAY_API_KEY')",
    "SMS_GATEWAY_WSDL=$(Get-EnvValue 'SMS_GATEWAY_WSDL')",
    "SMS_GATEWAY_SIGNATURE=$(Get-EnvValue 'SMS_GATEWAY_SIGNATURE')",
    "SMTP_HOST=$(Get-EnvValue 'SMTP_HOST')",
    "SMTP_PORT=$smtpPort",
    "SMTP_USER=$(Get-EnvValue 'SMTP_USER')",
    "SMTP_PASSWORD=$(Get-EnvValue 'SMTP_PASSWORD')",
    "",
    "LDAP_ENABLED=$(Get-EnvValue 'LDAP_ENABLED')",
    "LDAP_HOSTS=$(Get-EnvValue 'LDAP_HOSTS')",
    "LDAP_PORT=$(Get-EnvValue 'LDAP_PORT')",
    "LDAP_USE_SSL=$(Get-EnvValue 'LDAP_USE_SSL')",
    "LDAP_START_TLS=$(if ($startTls) { $startTls } else { 'false' })",
    "LDAP_CA_CERT_FILE=$(Get-EnvValue 'LDAP_CA_CERT_FILE')",
    "LDAP_BIND_DN=$(Get-EnvValue 'LDAP_BIND_DN')",
    "LDAP_BIND_PASSWORD=$(Get-EnvValue 'LDAP_BIND_PASSWORD')",
    "LDAP_BASE_DN=$(Get-EnvValue 'LDAP_BASE_DN')",
    "LDAP_USER_SEARCH_FILTER=$(Get-EnvValue 'LDAP_USER_SEARCH_FILTER')",
    "LDAP_TIMEOUT_SECONDS=$(Get-EnvValue 'LDAP_TIMEOUT_SECONDS')"
)

Set-Content -Path $dst -Value $out -Encoding UTF8
Write-Host "Wrote $dst"
Write-Host "Next: make up-senelec"
